import http from 'k6/http';
import { check } from 'k6';
import exec from 'k6/execution';

export const options = {
  scenarios: {
    open_model: {
      executor: 'constant-arrival-rate',
      rate: 16667, // Target RPM / 60
      timeUnit: '1s',
      duration: '30m',
      preAllocatedVUs: 2000,
      maxVUs: 10000,
    },
  },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080';

// Note: k6 needs to be able to find data.json
let data;
try {
  data = JSON.parse(open('./data.json'));
} catch (e) {
  data = { api_keys: ['test_token'], video_ids: ['vid_123'], buckets: ['bucket_1'], objects: ['obj_1'] };
}

const apiKeys = data.api_keys && data.api_keys.length > 0 ? data.api_keys : ['test_token'];
const videoIds = data.video_ids && data.video_ids.length > 0 ? data.video_ids : ['vid_123'];
const bucketIds = data.buckets && data.buckets.length > 0 ? data.buckets : ['bucket_1'];

export default function () {
  // Use execution ID to uniformly distribute across keys to simulate 100k distinct identities
  const vuApiKey = apiKeys[exec.scenario.iterationInTest % apiKeys.length];
  const params = {
    headers: {
      'Authorization': `Bearer ${vuApiKey}`,
      'Content-Type': 'application/json',
    },
  };

  const rand = Math.random();
  // 30% video list
  // 20% video detail
  // 15% playback metadata
  // 10% jobs
  // 10% buckets
  // 5% objects
  // 5% branding
  // 5% writes
  if (rand < 0.30) {
    const res = http.get(`${BASE_URL}/v1/videos`, params);
    check(res, { 'GET videos status 200': (r) => r.status === 200 });
  } else if (rand < 0.50) {
    const vid = videoIds[exec.scenario.iterationInTest % videoIds.length];
    const res = http.get(`${BASE_URL}/v1/videos/${vid}`, params);
    check(res, { 'GET video detail 200': (r) => r.status === 200 });
  } else if (rand < 0.65) {
    const vid = videoIds[exec.scenario.iterationInTest % videoIds.length];
    const res = http.get(`${BASE_URL}/v1/videos/${vid}/playback`, params);
    check(res, { 'GET video playback 200': (r) => r.status === 200 });
  } else if (rand < 0.75) {
    const res = http.get(`${BASE_URL}/v1/jobs`, params);
    check(res, { 'GET jobs status 200': (r) => r.status === 200 });
  } else if (rand < 0.85) {
    const res = http.get(`${BASE_URL}/v1/buckets`, params);
    check(res, { 'GET buckets status 200': (r) => r.status === 200 });
  } else if (rand < 0.90) {
    const bid = bucketIds[exec.scenario.iterationInTest % bucketIds.length];
    const res = http.get(`${BASE_URL}/v1/buckets/${bid}/objects`, params);
    check(res, { 'GET objects status 200': (r) => r.status === 200 });
  } else if (rand < 0.95) {
    const res = http.get(`${BASE_URL}/v1/branding`, params);
    check(res, { 'GET branding 200': (r) => r.status === 200 });
  } else {
    const payload = JSON.stringify({
      title: `Load Test Video ${exec.scenario.iterationInTest}`,
      description: 'Generated by k6 open loop'
    });
    const res = http.post(`${BASE_URL}/v1/videos`, payload, params);
    check(res, { 'POST video 201': (r) => r.status === 201 });
  }
}
